const DICTS: Record<Lang, Record<Key, string>> = { uk, en }
export type TKey = Key
type T = (key: Key, vars?: Record<string, string | number>) => string

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: T; fmtDate: (s: string) => string; fmtNum: (n: number) => string } | null>(null)

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('hethereau-ledger.lang')
    if (saved === 'uk' || saved === 'en') return saved
  } catch {
    /* ignore */
  }
  return navigator.language?.toLowerCase().startsWith('uk') ? 'uk' : 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(initialLang)
  useEffect(() => {
    document.documentElement.lang = lang
    try {
      localStorage.setItem('hethereau-ledger.lang', lang)
    } catch {
      /* ignore */
    }
  }, [lang])
  const value = useMemo(() => {
    const dict = DICTS[lang]
    const t: T = (key, vars) => {
      let s = dict[key] ?? key
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
      return s
    }
    const fmt = new Intl.DateTimeFormat(lang === 'uk' ? 'uk-UA' : 'en-GB', { day: 'numeric', month: 'short', year: 'numeric' })
    const fmtDate = (s: string) => {
      const d = new Date(s.includes('T') ? s : s.replace(' ', 'T'))
      return Number.isNaN(d.getTime()) ? s : fmt.format(d)
    }
    const num = new Intl.NumberFormat(lang === 'uk' ? 'uk-UA' : 'en-GB')
    const fmtNum = (n: number) => num.format(n)
    return { lang, setLang, t, fmtDate, fmtNum }
  }, [lang])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n() {
  const v = useContext(Ctx)
  if (!v) throw new Error('I18nProvider missing')
  return v
}
